class Vacancy:
    """Класс представления вакансии"""

    __slots__ = ("vacancy_id", "name", "area", "salary_from", "url", "snippet_requirement", "snippet_responsibility")

    def __init__(
        self,
        vacancy_id,
        name,
        area,
        salary_from,
        url,
        snippet_requirement,
        snippet_responsibility,
    ):
        self.vacancy_id = vacancy_id
        self.name = name
        self.area = area
        self.salary_from = salary_from
        self.url = url
        self.snippet_requirement = snippet_requirement
        self.snippet_responsibility = snippet_responsibility



    def __lt__(self, other: "Vacancy") -> bool:
        return self.salary_from < other.salary_from

    def __str__(self):
        return (f"ID: {self.vacancy_id}\n"
                f"Название вакансии: {self.name}\n"
                f"Зарплата от: {self.salary_from}\n"
                f"Местоположение: {self.area}\n"
                f"Ссылка на вакансию: {self.url}\n"
                f"Описание: {self.snippet_requirement}\n{self.snippet_responsibility}\n-------")

    def __repr__(self):
        return f"{self.salary_from}"

    @classmethod
    def cast_to_object_list(cls, object_list):
        """Преобразование JSON файла в объект класса"""
        vacancies_object = []
        for item in object_list:
            vacancy_id = item.get("id")
            name = item.get("name", "")
            area = item.get("area").get("name", "")
            salary = item.get("salary")
            if salary is None:
                salary_from = 0
            else:
                salary_from = item.get("salary").get("from")
                if salary_from is None:
                    salary_from = 0
            url = (item.get("alternate_url", ""),)
            if item.get("snippet", "").get("requirement") is None:
                snippet_requirement = None
            else:
                snippet_requirement = (clean_search_teg(item.get("snippet", "").get("requirement")),)
            if item.get("snippet", "").get("requirement") is None:
                snippet_responsibility = None
            else:
                snippet_responsibility = clean_search_teg(item.get("snippet", "").get("requirement"))
            vacancy = cls(
                vacancy_id=vacancy_id,
                name=name,
                area=area,
                salary_from=salary_from,
                url=url,
                snippet_requirement=snippet_requirement,
                snippet_responsibility=snippet_responsibility,
            )
            vacancies_object.append(vacancy)
        return vacancies_object


